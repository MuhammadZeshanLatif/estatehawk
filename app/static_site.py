"""Build the public website as plain files for a static host (SymbolHost), and ask GitHub to rebuild it.

    python -m app.static_site build [out_dir]

The pages are the same HTML the server renders today. Links that belong to the product
(login, signup, dashboard, API) are pointed at APP_URL, so the static host only serves the website.
"""
import base64, os, re, shutil, sys, threading
from pathlib import Path

import requests
from starlette.requests import Request

from . import content, db, site

ROOT = db.ROOT
WEB = os.path.join(ROOT, "web")
EXT = {"image/jpeg": "jpg", "image/png": "png", "image/webp": "webp"}

HTACCESS = r"""# EstateHawk website (generated by app/static_site.py; do not edit on the server)
Options -MultiViews -Indexes
DirectorySlash Off
DirectoryIndex index.html
ErrorDocument 404 /404.html

<IfModule mod_rewrite.c>
RewriteEngine On

# one address: https and no www
RewriteCond %{HTTPS} !=on [OR]
RewriteCond %{HTTP_HOST} ^www\. [NC]
RewriteRule ^ https://{SITE_HOST}%{REQUEST_URI} [R=301,L]

# the product (sign in, dashboard, API, email links) lives on the app host
RewriteRule ^({APP_PATHS})(/.*)?$ {APP_URL}%{REQUEST_URI} [R=301,L]

# /page.html and /page/ are the same page as /page
RewriteCond %{THE_REQUEST} \s/+([^?\s]+?)\.html[\s?]
RewriteRule ^ /%1 [R=301,L]
RewriteRule ^(.+)/$ /$1 [R=301,L]

# /blog/my-post serves blog/my-post.html
RewriteCond %{DOCUMENT_ROOT}/$1.html -f
RewriteRule ^(.+)$ $1.html [L]
</IfModule>

<IfModule mod_headers.c>
Header always set X-Content-Type-Options "nosniff"
Header always set X-Frame-Options "SAMEORIGIN"
Header always set Referrer-Policy "strict-origin-when-cross-origin"
Header always set Strict-Transport-Security "max-age=31536000; includeSubDomains"
<FilesMatch "\.html$">
Header set Cache-Control "public, max-age=300"
</FilesMatch>
<FilesMatch "\.(css|js|svg|png|jpg|webp|woff2)$">
Header set Cache-Control "public, max-age=604800"
</FilesMatch>
</IfModule>

<IfModule mod_deflate.c>
AddOutputFilterByType DEFLATE text/html text/css application/javascript application/xml text/plain image/svg+xml
</IfModule>
"""


def _request(path):
    host = site.CANONICAL.split("://", 1)[1]
    scope = {"type": "http", "method": "GET", "path": "/" + path, "raw_path": ("/" + path).encode(), "query_string": b"",
             "headers": [(b"host", host.encode())], "scheme": "https", "server": (host, 443), "client": ("127.0.0.1", 0),
             "root_path": "", "app": None}
    req = Request(scope)
    req.state.site_user = None  # a static page is the same for everyone
    return req


def _product_links(html_, app):
    """Point login/signup/dashboard/API links at the app host; leave website links alone."""
    paths = "|".join(re.escape(p) for p in site.APP_PATHS if p not in ("static", "blog-media"))
    rx = re.compile(r'((?:href|action|data-api|data-next)=["\'])/((?:' + paths + r')(?:[/?#][^"\']*)?)(["\'])')
    html_ = rx.sub(lambda m: f"{m.group(1)}{app}/{m.group(2)}{m.group(3)}", html_)
    return html_.replace("'/api/", f"'{app}/api/")  # sign-up-with-Google link built in the page script


def _write(out, rel, data):
    path = os.path.join(out, *rel.strip("/").split("/"))
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "wb" if isinstance(data, bytes) else "w", **({} if isinstance(data, bytes) else {"encoding": "utf-8", "newline": "\n"})) as f:
        f.write(data)


def site_paths():
    """Every public page: the sitemap list, plus the blog index even when it is empty."""
    req = _request("sitemap.xml")
    urls = re.findall(r"<loc>[^<]*?getestatehawk\.com/?([^<]*)</loc>", site.sitemap(req)) or [""]
    urls = [u for u in urls if not site.is_app_path(u)]
    if "blog" not in urls:
        urls.append("blog")
    return urls


def build(out):
    app = site.app_url()
    if app == site.CANONICAL:
        raise SystemExit("Set APP_URL (for example https://app.getestatehawk.com) before building the static site.")
    content.publish_due()
    if os.path.isdir(out):
        shutil.rmtree(out)
    os.makedirs(out)
    media, pages = set(), 0
    for path in site_paths() + ["__404__"]:
        req = _request(path)
        html_ = site.not_found(req) if path == "__404__" else site.render(req, path)
        if html_ is None:
            continue
        html_ = _product_links(html_, app)
        media.update(re.findall(r"/blog-media/(\d+)(?:/([a-z0-9._-]+))?", html_))
        _write(out, "404.html" if path == "__404__" else (path or "index") + ".html", html_)
        pages += 1
    # Images uploaded in the blog editor live in the database; the static host gets real files.
    # The editor's /blog-media/<id>/<name>.jpg form is kept as is; the bare /blog-media/<id> form gets an extension.
    rewrite = {}
    for image_id in sorted({i for i, _ in media}, key=int):
        row = db.q1("SELECT mime,data FROM blog_images WHERE id=?", (int(image_id),))
        if not row:
            continue
        data = base64.b64decode(row["data"])
        rewrite[image_id] = f"/blog-media/{image_id}.{EXT.get(row['mime'], 'jpg')}"
        _write(out, rewrite[image_id], data)
        for name in {n for i, n in media if i == image_id and n}:
            _write(out, f"/blog-media/{image_id}/{name}", data)
    if rewrite:
        for rel, html_ in _pages(out):
            fixed = re.sub(r"/blog-media/(\d+)(?![\d/.])", lambda m: rewrite.get(m.group(1), m.group(0)), html_)
            if fixed != html_:
                _write(out, rel, fixed)
    # website assets: the site folder, and only the /static files the pages use (not the dashboard code)
    shutil.copytree(os.path.join(WEB, "site"), os.path.join(out, "site"))
    used = set()
    for _, html_ in _pages(out):
        used.update(re.findall(r'/static/([A-Za-z0-9_.-]+)', html_))
    todo = sorted(used)
    while todo:  # also files the scripts and styles load themselves
        name = todo.pop()
        src = Path(WEB, name)
        if not src.is_file() or Path(out, "static", name).exists():
            continue
        _write(out, f"/static/{name}", src.read_bytes())
        if name.endswith((".js", ".css")):
            todo += re.findall(r"/static/([A-Za-z0-9_.-]+)", src.read_text(encoding="utf-8"))
        if name.endswith(".js"):
            todo += re.findall(r"""from\s+['"]\./([A-Za-z0-9_.-]+\.js)['"]""", src.read_text(encoding="utf-8"))
    widget = Path(out, "static", "chat-widget.js")
    if widget.exists():
        js = widget.read_text(encoding="utf-8")
        # On the website nobody is signed in (the session cookie lives on the app host), so skip the account check.
        js = js.replace("fetch('/api/auth/me', { credentials: 'same-origin' })", "Promise.resolve({ ok: false })")
        js = js.replace("'/api/public/", f"'{app}/api/public/")
        _write(out, "/static/chat-widget.js", js)
    req = _request("sitemap.xml")
    sitemap = re.sub(r"<url><loc>[^<]*/(?:" + "|".join(re.escape(p) for p in site.APP_PATHS) + r")(?:/[^<]*)?</loc>(?:<lastmod>[^<]*</lastmod>)?</url>", "", site.sitemap(req))
    _write(out, "sitemap.xml", sitemap)
    _write(out, "robots.txt", site.robots(req))
    _write(out, ".htaccess", HTACCESS.replace("{SITE_HOST}", site.CANONICAL.split("://", 1)[1])
           .replace("{APP_URL}", app).replace("{APP_PATHS}", "|".join(re.escape(p) for p in site.APP_PATHS if p not in ("static", "blog-media"))))
    print(f"Static site built in {out}: {pages} pages, {len(rewrite)} images.")
    return pages


def _pages(out):
    for folder, _, files in os.walk(out):
        for name in files:
            if name.endswith(".html"):
                full = os.path.join(folder, name)
                yield os.path.relpath(full, out).replace(os.sep, "/"), Path(full).read_text(encoding="utf-8")


# ------------------------------------------------------------------ rebuild after a blog change
def request_rebuild(reason="blog"):
    """Ask GitHub Actions to rebuild and upload the website. Quietly does nothing until it is set up."""
    token, repo = os.environ.get("SITE_PUBLISH_TOKEN"), os.environ.get("SITE_PUBLISH_REPO")
    if not token or not repo:
        return False

    def send():
        try:
            requests.post(f"https://api.github.com/repos/{repo}/dispatches", timeout=15,
                          headers={"Authorization": f"Bearer {token}", "Accept": "application/vnd.github+json"},
                          json={"event_type": "publish-site", "client_payload": {"reason": reason}})
        except requests.RequestException:
            pass  # the daily rebuild still picks the change up

    threading.Thread(target=send, daemon=True).start()
    return True


if __name__ == "__main__":
    if len(sys.argv) >= 2 and sys.argv[1] == "build":
        build(sys.argv[2] if len(sys.argv) > 2 else os.path.join(ROOT, "dist", "site"))
    else:
        print(__doc__)
